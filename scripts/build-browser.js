// Bundle the CommonJS stroke expander into one browser-ready global file.
// It wraps each source module in a local require/module shim, preserving the
// original CommonJS sources untouched.
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'src');
const order = [
  'geometry.js',
  'path-parser.js',
  'flatten.js',
  'dasher.js',
  'stroker.js',
  'stroke-to-path.js',
];

const blocks = order.map((file) => {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const key = `'./${file.replace(/\.js$/, '')}'`;
  return `  ${key}: function (module, exports, require) {\n${source}\n  },`;
});

const output = `// Auto-generated by scripts/build-browser.js. Do not edit.
(function () {
  var registry = {
${blocks.join('\n')}
  };
  var cache = {};
  function require(name) {
    var file = name.replace('./', '') + '.js';
    if (cache[file]) return cache[file].exports;
    var module = { exports: {} };
    cache[file] = module;
    var key = name.startsWith('./') ? name : './' + name;
    registry[key](module, module.exports, require);
    return module.exports;
  }
  window.StrokeToPath = require('./stroke-to-path');
})();
`;

fs.writeFileSync(path.join(__dirname, '..', 'dist', 'stroke-to-path.browser.js'), output);
console.log('wrote dist/stroke-to-path.browser.js');
